import Foundation

public extension LemmyApi {
    /// Permanently delete the logged-in account.
    /// - Parameters:
    ///   - deleteContent: Whether to also delete all content created by the account.
    func deleteAccount(
        password: Swift.String,
        deleteContent: Swift.Bool
    ) async throws -> Components.Schemas.SuccessResponse {
        let response: Operations.deleteAccount.Output
        do {
            response = try await client.deleteAccount(body: .json(.init(
                password: password,
                delete_content: deleteContent
            )))
        } catch {
            throw LemmyApiError(from: error)
        }

        switch response {
        case let .ok(response):
            switch response.body {
            case let .json(json):
                return json
            }

        case let .unauthorized(response):
            switch response.body {
            case let .json(json):
                switch json.error {
                case .incorrect_login:
                    throw LemmyApiError.unauthorized(message: json.message)
                }
            }

        case let .badRequest(response):
            switch response.body {
            case let .json(json):
                throw LemmyApiError.serverError(json)
            }

        case let .undocumented(statusCode, _):
            throw LemmyApiError.unknownServerError(httpStatusCode: statusCode, error: nil)
        }
    }
}
