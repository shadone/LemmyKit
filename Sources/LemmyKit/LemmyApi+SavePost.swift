import Foundation

public extension LemmyApi {
    /// Save or unsave the post `postID` for the logged-in account.
    func savePost(
        postID: Components.Schemas.PostID,
        save: Bool
    ) async throws -> Components.Schemas.PostResponse {
        let response: Operations.savePost.Output
        do {
            response = try await client.savePost(body: .json(.init(
                post_id: postID,
                save: save
            )))
        } catch {
            throw LemmyApiError(from: error)
        }

        switch response {
        case let .ok(response):
            switch response.body {
            case let .json(json):
                return json
            }

        case let .unauthorized(response):
            switch response.body {
            case let .json(json):
                switch json.error {
                case .incorrect_login:
                    throw LemmyApiError.unauthorized(message: json.message)
                }
            }

        case let .badRequest(response):
            switch response.body {
            case let .json(json):
                throw LemmyApiError.serverError(json)
            }

        case let .undocumented(statusCode, _):
            throw LemmyApiError.unknownServerError(httpStatusCode: statusCode, error: nil)
        }
    }
}
