import Foundation

public extension LemmyApi {
    /// Block or unblock the community `communityID` for the logged-in account.
    func blockCommunity(
        communityID: Components.Schemas.CommunityID,
        block: Bool
    ) async throws -> Components.Schemas.BlockCommunityResponse {
        let response: Operations.blockCommunity.Output
        do {
            response = try await client.blockCommunity(body: .json(.init(
                community_id: communityID,
                block: block
            )))
        } catch {
            throw LemmyApiError(from: error)
        }

        switch response {
        case let .ok(response):
            switch response.body {
            case let .json(json):
                return json
            }

        case let .unauthorized(response):
            switch response.body {
            case let .json(json):
                switch json.error {
                case .incorrect_login:
                    throw LemmyApiError.unauthorized(message: json.message)
                }
            }

        case let .badRequest(response):
            switch response.body {
            case let .json(json):
                throw LemmyApiError.serverError(json)
            }

        case let .undocumented(statusCode, _):
            throw LemmyApiError.unknownServerError(httpStatusCode: statusCode, error: nil)
        }
    }
}
