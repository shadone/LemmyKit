import Foundation

public extension LemmyApi {
    /// Fetch the instances this instance is federated with (linked, allowed,
    /// and blocked).
    func getFederatedInstances() async throws -> Components.Schemas.GetFederatedInstancesResponse {
        let response: Operations.getFederatedInstances.Output
        do {
            response = try await client.getFederatedInstances()
        } catch {
            throw LemmyApiError(from: error)
        }

        switch response {
        case let .ok(response):
            switch response.body {
            case let .json(json):
                return json
            }

        case let .badRequest(response):
            switch response.body {
            case let .json(json):
                throw LemmyApiError.serverError(json)
            }

        case let .undocumented(statusCode, _):
            throw LemmyApiError.unknownServerError(httpStatusCode: statusCode, error: nil)
        }
    }
}
