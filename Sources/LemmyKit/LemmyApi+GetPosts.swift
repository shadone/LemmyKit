import Foundation

extension LemmyApi {
    /// Shared transport and response decoding for the public `getPosts`
    /// overloads. Each overload builds the query for its scope and forwards
    /// here.
    func getPosts(
        query: Operations.getPosts.Input.Query
    ) async throws -> Components.Schemas.GetPostsResponse {
        let response: Operations.getPosts.Output
        do {
            response = try await client.getPosts(.init(query: query))
        } catch {
            throw LemmyApiError(from: error)
        }

        switch response {
        case let .ok(response):
            switch response.body {
            case let .json(json):
                return json
            }

        case let .unauthorized(response):
            switch response.body {
            case let .json(json):
                switch json.error {
                case .incorrect_login:
                    throw LemmyApiError.unauthorized(message: json.message)
                }
            }

        case let .badRequest(response):
            switch response.body {
            case let .json(json):
                throw LemmyApiError.serverError(json)
            }

        case let .undocumented(statusCode, _):
            throw LemmyApiError.unknownServerError(httpStatusCode: statusCode, error: nil)
        }
    }
}
